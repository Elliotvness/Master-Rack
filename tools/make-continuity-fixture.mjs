#!/usr/bin/env node
/**
 * make-continuity-fixture — export what the v1 prototype computes, verbatim.
 *
 * Build-plan **S0.2**. The fixture exists so the µm re-derivation can be shown
 * not to have changed an answer: DEC-2 settled micrometres, 1 mil = 25.4 µm is
 * not an integer, and allocation over a remainder lands differently in the two
 * bases. Asserting equality would be wrong; recording the delta is the point.
 *
 * **Produced by a script, not typed.** That is S0.2's stated acceptance, and it
 * is not pedantry — a hand-typed fixture is a second opinion written by the
 * person who already holds the first one. Re-running this yields a
 * byte-identical file.
 *
 * SOURCE, and why reading it is safe: the prototype lives at
 * `C:\Rack Master\rack-studio-v1.tar_1\prototype`, which is NOT inside
 * `Resourse (do not delete or overwrite files)`. It is opened read-only either
 * way — this script imports two pure functions and writes nothing back.
 *
 * The document is emitted in **mil**, exactly as the prototype holds it. No
 * conversion happens here on purpose: converting at export would put the very
 * arithmetic under test into the fixture that is supposed to judge it.
 *
 * Usage:  node tools/make-continuity-fixture.mjs [--check]
 *   --check  regenerate into memory and fail if it differs from the file on
 *            disk, without writing. This is the arm CI would use.
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** The prototype tree. Overridable so the self-test can point elsewhere. */
export const PROTOTYPE_DIR =
  process.env['RMS_PROTOTYPE_DIR'] ??
  resolve(ROOT, '..', 'rack-studio-v1.tar_1', 'prototype');

export const FIXTURE_PATH = join(ROOT, 'fixtures', 'continuity', 'rack-studio-v1.json');

/** sha256 of the prototype kernel, so the fixture names what produced it. */
function kernelDigest(dir) {
  const source = readFileSync(join(dir, 'kernel.js'));
  return `sha256:${createHash('sha256').update(source).digest('hex')}`;
}

export async function buildFixture(dir = PROTOTYPE_DIR) {
  const kernel = await import(pathToFileURL(join(dir, 'kernel.js')).href);
  const document = kernel.newDocument();

  return {
    $comment:
      'GENERATED by tools/make-continuity-fixture.mjs. Do not edit by hand. ' +
      'Lengths are in MIL (thousandths of an inch), as the v1 prototype holds them — ' +
      'not converted, because converting here would put the arithmetic under test ' +
      'into the fixture meant to judge it.',
    source: {
      prototype: 'rack-studio-v1/prototype/kernel.js',
      kernelSha256: kernelDigest(dir),
      schemaVersion: kernel.SCHEMA_VERSION,
      lengthUnit: 'mil',
    },
    document,
  };
}

/** Stable serialisation. Two runs must differ in no byte. */
export function serialise(fixture) {
  return `${JSON.stringify(fixture, null, 2)}\n`;
}

async function main() {
  const check = process.argv.includes('--check');
  const text = serialise(await buildFixture());

  if (!check) {
    writeFileSync(FIXTURE_PATH, text, 'utf8');
    console.log(`make-continuity-fixture: wrote ${FIXTURE_PATH} (${text.length} bytes)`);
    return;
  }

  let existing;
  try {
    existing = readFileSync(FIXTURE_PATH, 'utf8');
  } catch {
    console.error('make-continuity-fixture: FAIL — the fixture does not exist. Run without --check.');
    process.exitCode = 1;
    return;
  }
  if (existing !== text) {
    console.error(
      'make-continuity-fixture: FAIL — the prototype now produces a different document ' +
        'than the committed fixture. That is a real change and needs a reason, not a regenerate.',
    );
    process.exitCode = 1;
    return;
  }
  console.log('make-continuity-fixture: PASS — the fixture matches what the prototype produces.');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main();
}
