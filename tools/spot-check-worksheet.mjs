#!/usr/bin/env node
/**
 * spot-check-worksheet — turn a pinned draw into something a person can read
 * off a PDF without losing their place.
 *
 * The draw is random by design, so the pinned order jumps between tables and
 * pages. Reading it in that order means forty-two page turns. This regroups the
 * SAME cells by page and table and sorts within each, so the job is three
 * passes down three charts. It changes nothing about which cells were drawn —
 * `record-spot-check.mjs` copies them from the manifest verbatim, in the drawn
 * order, so the gate's comparison is unaffected.
 *
 * Each row carries what the extract CLAIMS. Read the published value, and tick
 * or write down the real one. Any mismatch fails the whole release: one wrong
 * cell means a defect of unknown extent, and there is no partial pass.
 *
 *   node tools/spot-check-worksheet.mjs interlake-2026-09 > tasks/spot-check-worksheet.md
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const dir = process.argv[2] ?? 'interlake-2026-09';
const at = (f) => join(ROOT, 'data/catalog', dir, f);
const read = (f) => JSON.parse(readFileSync(at(f), 'utf8'));

const manifest = read('manifest.json');
const pending = manifest.pending_spot_checks ?? [];
if (pending.length === 0) {
  console.error(`${dir} has no pinned draw. Run: node tools/draw-spot-check.mjs ${dir}`);
  process.exit(1);
}

const out = [];
const p = (s = '') => out.push(s);

p(`# Spot-check worksheet — \`${dir}\``);
p();
p(`Generated by \`tools/spot-check-worksheet.mjs\` from the draw pinned in \`manifest.json\`.`);
p(`**Do not re-draw.** A sample that can be redrawn until it is convenient is not a random sample.`);
p();
p(`**Source:** ${manifest.source_document}`);
p();
p(`**The rule (§10.2).** The tool drew these cells; you read them off the published chart. Any`);
p(`mismatch fails the entire release — no partial pass, no "approve with notes". One wrong cell`);
p(`means the extract has a defect of unknown extent, and the remedy is a corrected extract, not a`);
p(`note. If every cell matches, run the recorder at the bottom of this file.`);
p();
p(`Cells below are regrouped by page for reading. The recorded order is handled for you.`);
p();

for (const entry of pending) {
  const { dataset, cells, seed, sampled_cells: sampled } = entry;
  p(`---`);
  p();
  p(`## ${dataset} — ${sampled.length} of ${cells} cells (seed ${seed})`);
  p();

  if (dataset === 'beams') {
    const rows = read('beams.json').rows;
    const byId = new Map(rows.map((r) => [`${r.family}/${r.series}/${r.span_in}in`, r]));
    p(`Chart: **p.88** — 'BEAM WITH TAB END PLATE CAPACITY CHART: 27E – 65Q, 48"–168"'.`);
    p(`Capacities are **lbs per PAIR of beams**, the lesser of bending strength and L/180 deflection,`);
    p(`product load plus dead load. The end-plate model (F3M / F4M / F5M, p.83) is characters 6–8 of`);
    p(`the 18-digit code; the family (p.84) is characters 3–5.`);
    p();
    p(`| ✓ | Family | End plate | Span | **Capacity claimed (lbs/pair)** | Face height (in) | Deflection (in) | Part number |`);
    p(`|---|---|---|---|---|---|---|---|`);
    const sorted = [...sampled].sort((a, b) => {
      const A = byId.get(a), B = byId.get(b);
      return A.family.localeCompare(B.family) || A.span_in - B.span_in;
    });
    for (const id of sorted) {
      const r = byId.get(id);
      p(`| ☐ | ${r.family} | ${r.series} | ${r.span_in}" | **${r.capacity_lbs.toLocaleString()}** | ${r.face_height_in} | ${r.deflection_in} | \`${r.part_number}\` |`);
    }
    p();
    p(`> Note: an \`R\` suffix on the family (59ER, 65QR, 40ER) marks the reinforced/heavier variant.`);
    p(`> Check you are on the right row of the chart before comparing the number.`);
    p();
    continue;
  }

  if (dataset === 'frames') {
    const tables = read('frames.json').tables;
    const byId = new Map();
    for (const t of tables) {
      for (const [hbl, values] of Object.entries(t.rows)) {
        values.forEach((v, i) =>
          byId.set(`${t.table_id}/HbL${hbl}/col${i}`, {
            table: t.table_id,
            page: t.page_ref,
            column: t.column_order[i],
            hbl: Number(hbl),
            value: v,
          }),
        );
      }
    }
    const groups = new Map();
    for (const id of sampled) {
      const c = byId.get(id);
      if (!groups.has(c.page)) groups.set(c.page, []);
      groups.get(c.page).push(c);
    }
    p(`Capacities are **lbs per PAIR of frames**, product load plus dead load (dead load = 2% of`);
    p(`product load), static only, FY = 55 KSI, per ANSI MH16.1-2012.`);
    p();
    p(`**HbL** is the maximum unsupported span: the largest beam spacing, *or* floor-to-top-of-first-beam,`);
    p(`whichever is greater. **@<=21ft / @>21ft** is the overall frame height band — the banded models`);
    p(`have two strut patterns and therefore two columns; the unbanded ones have one.`);
    p();
    // By page NUMBER, not lexically: 'p.8' sorts after 'p.52' as a string, which
    // sends the reader backwards through the PDF for no reason.
    const pageNo = (s) => Number(/p\.(\d+)/.exec(s)?.[1] ?? Number.MAX_SAFE_INTEGER);
    for (const [page, cellsOnPage] of [...groups].sort((a, b) => pageNo(a[0]) - pageNo(b[0]))) {
      p(`### ${page}`);
      p();
      p(`| ✓ | Column (model @ band) | HbL (in) | **Capacity claimed (lbs/pair)** |`);
      p(`|---|---|---|---|`);
      for (const c of cellsOnPage.sort((a, b) => a.column.localeCompare(b.column) || a.hbl - b.hbl)) {
        p(`| ☐ | ${c.column} | ${c.hbl} | **${c.value.toLocaleString()}** |`);
      }
      p();
    }
    continue;
  }

  p(`_No worksheet renderer for '${dataset}'. Add one before a release ships it._`);
  p();
}

p(`---`);
p();
p(`## When every cell matches`);
p();
p('```');
p(`node tools/record-spot-check.mjs ${dir} --checked-by "Your Name" --matched`);
p('```');
p();
p(`It copies the pinned cells verbatim into \`human_spot_checks\`, in the drawn order. It will not`);
p(`let you record cells other than the ones drawn — that is the whole point of the gate, and`);
p(`hand-editing the JSON is how you spend an hour reading a chart and then get refused on a typo.`);
p();
p(`\`--matched\` is required and has no default: a default would be a signature nobody typed.`);
p();
p(`## If any cell does not match`);
p();
p('```');
p(`node tools/record-spot-check.mjs ${dir} --checked-by "Your Name" \\`);
p(`  --failed "59E/F5M/120in reads 7530 on p.88, extract says 7330"`);
p('```');
p();
p(`Do not record a partial pass. One wrong cell fails the WHOLE release: it means the extract has`);
p(`a defect of unknown extent, so the remedy is a corrected extract and a fresh draw, not a note.`);
p(`\`${dir}\` stays DRAFT until then.`);
p();
p(`That is not a setback. It is the control doing the only job it has, and it is the job the`);
p(`reference data's 72% overstatement got through because nobody was doing.`);

console.log(out.join('\n'));
